#!/usr/bin/env python3
"""Generate counting hooks for Fable II's D3D-library candidate functions.

Every function start inside the D3D clusters gets a strong-symbol override
(like svr2011's d3d_trace_hooks.cpp) that calls fable2::census::OnCall() and
then the original generated body:

    REX_EXTERN(__imp__sub_XXXXXXXX);
    REX_HOOK_RAW(sub_XXXXXXXX) {
      fable2::census::OnCall(<index>, ctx, base);
      __imp__sub_XXXXXXXX(ctx, base);
    }

Hotfunc-override addresses (already strong symbols elsewhere) are excluded so
the link does not see duplicates.

    python gen_d3d_census_hooks.py --gen port/generated/default \
        --out port/src/d3d_census_hooks.cpp
"""
import argparse
import glob
import os
import re

DEFAULT_RANGES = [
    (0x821F0000, 0x822A0000),  # draws / vertex streams / resources
    (0x82B90000, 0x82BB0000),  # device, ring, display, present
    (0x82F60000, 0x82F70000),  # shader registration / larger device code
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--gen', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--hotfunc', default='port/src/core/hotfunc')
    ap.add_argument('--ranges', default='')
    a = ap.parse_args()

    ranges = DEFAULT_RANGES
    if a.ranges:
        ranges = []
        for part in a.ranges.split(','):
            lo, hi = part.split('-')
            ranges.append((int(lo, 16), int(hi, 16)))

    hotfunc_addrs = set()
    for p in glob.glob(os.path.join(a.hotfunc, '**', '*.cpp'), recursive=True):
        m = re.search(r'_([0-9A-Fa-f]{8})\.cpp$', p)
        if m:
            hotfunc_addrs.add(int(m.group(1), 16))

    names = {}
    for path in glob.glob(os.path.join(a.gen, '*_recomp.*.cpp')):
        for m in re.finditer(r'^DEFINE_REX_FUNC\((sub_([0-9A-Fa-f]{8}))\)',
                             open(path, errors='replace').read(), re.M):
            addr = int(m.group(2), 16)
            if any(lo <= addr < hi for lo, hi in ranges):
                names[addr] = m.group(1)

    entries = []
    for addr in sorted(names):
        if addr in hotfunc_addrs:
            continue
        entries.append((addr, names[addr]))

    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, 'w') as f:
        f.write('// Generated by tools/deko3d/gen_d3d_census_hooks.py - do not edit.\n')
        f.write('// Counting hooks on Fable II\'s D3D-library candidate functions.\n\n')
        f.write('#include <rex/hook.h>\n#include <rex/ppc.h>\n\n')
        f.write('#include "d3d_census.h"\n\n')
        f.write('namespace fable2::census {\n\n')
        f.write('extern const uint32_t kFunctionCount = %d;\n' % len(entries))
        f.write('extern const uint32_t kFunctionAddr[] = {\n')
        for addr, _ in entries:
            f.write('    0x%08X,\n' % addr)
        f.write('};\n')
        f.write('extern const char* const kFunctionName[] = {\n')
        for _, name in entries:
            f.write('    "%s",\n' % name)
        f.write('};\n\n')
        f.write('}  // namespace fable2::census\n\n')
        for i, (addr, name) in enumerate(entries):
            f.write('REX_EXTERN(__imp__%s);\n' % name)
            f.write('REX_HOOK_RAW(%s) {\n' % name)
            f.write('  fable2::census::OnCall(%d, ctx, base);\n' % i)
            f.write('  __imp__%s(ctx, base);\n' % name)
            f.write('}\n\n')
    print(f'{len(entries)} hooks -> {a.out} ({len(hotfunc_addrs)} hotfunc addresses excluded)')


if __name__ == '__main__':
    main()
